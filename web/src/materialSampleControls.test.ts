import {afterEach, describe, expect, it, vi} from 'vitest';
import {Euler, Quaternion} from 'three';
import {bindMaterialSampleControls} from './materialSampleControls';

class SampleControl extends EventTarget {
  disabled = false;
  dataset: Record<string, string> = {};
  ownerDocument = Object.assign(new EventTarget(), {defaultView: new EventTarget()});
  focus = vi.fn();
  captured = new Set<number>();
  getBoundingClientRect = () => ({x:100, y:200, left:100, top:200, right:284, bottom:384, width:184, height:184, toJSON:()=>({})});
  setPointerCapture = vi.fn((id: number) => {this.captured.add(id);});
  hasPointerCapture = (id: number) => this.captured.has(id);
  releasePointerCapture = vi.fn((id: number) => {
    if (this.captured.delete(id)) emit(this, 'lostpointercapture', {pointerId:id});
  });
}
function emit(target: EventTarget, type: string, fields: Record<string, unknown> = {}) {
  const event = Object.assign(new Event(type, {bubbles:true, cancelable:true}), fields);
  target.dispatchEvent(event);
  return event;
}
function pointer(control: SampleControl, type: string, x=140, y=250, fields: Record<string, unknown> = {}) {
  return emit(control, type, {pointerId:1, pointerType:'mouse', isPrimary:true, button:0, buttons:type==='pointerup'?0:1, clientX:x, clientY:y, ...fields});
}
function keyboard(control: SampleControl, key: string, fields: Record<string, unknown> = {}) {
  return emit(control, 'keydown', {key, ctrlKey:false, metaKey:false, altKey:false, shiftKey:false, ...fields});
}
const disposals: Array<() => void> = [];
afterEach(() => {disposals.splice(0).forEach(dispose => dispose());});
function specimen(initial = new Quaternion()) {
  const control = new SampleControl(), orientation = initial.clone(), invalidate = vi.fn(), onRelease = vi.fn();
  const binding = bindMaterialSampleControls(control as unknown as HTMLButtonElement, orientation, invalidate, onRelease);
  disposals.push(binding.dispose);
  return {control, orientation, invalidate, onRelease, binding};
}
function expectSamePose(actual: Quaternion, expected: Quaternion) {
  expect(actual.angleTo(expected)).toBeLessThan(1e-7);
}

describe('material sample drag lifecycle', () => {
  it('produces the same diagonal pose with sparse or dense pointer events', () => {
    const start = new Quaternion().setFromEuler(new Euler(.2, -.4, .1));
    const sparse = specimen(start), dense = specimen(start);
    for (const {control} of [sparse, dense]) pointer(control, 'pointerdown');
    pointer(sparse.control, 'pointermove', 220, 305);
    for (let i=1; i<=100; i++) pointer(dense.control, 'pointermove', 140+80*i/100, 250+55*i/100);
    for (const {control} of [sparse, dense]) pointer(control, 'pointerup', 220, 305);
    expectSamePose(sparse.orientation, dense.orientation);
    expect(sparse.orientation.angleTo(start)).toBeGreaterThan(.1);
  });
  it('returns exactly to the starting pose when the pointer returns during a drag', () => {
    const initial = new Quaternion().setFromEuler(new Euler(.3, .4, -.2));
    const {control, orientation, binding} = specimen(initial);
    pointer(control, 'pointerdown'); pointer(control, 'pointermove', 240, 310);
    pointer(control, 'pointermove', 160, 220); pointer(control, 'pointerup', 140, 250);
    expectSamePose(orientation, initial); expect(binding.isDragging()).toBe(false);
  });
  it('does not reset after a double-click generated by rapid successive drags', () => {
    const {control, orientation} = specimen();
    pointer(control, 'pointerdown'); pointer(control, 'pointerup', 210, 270); emit(control, 'click', {detail:1});
    pointer(control, 'pointerdown', 210, 270); pointer(control, 'pointerup', 170, 300); emit(control, 'click', {detail:2});
    const afterDrag = orientation.clone(); emit(control, 'dblclick', {detail:2});
    expectSamePose(orientation, afterDrag); expect(orientation.angleTo(new Quaternion())).toBeGreaterThan(.1);
  });
  it('still resets for two stationary clicks', () => {
    const {control, orientation} = specimen(new Quaternion().setFromEuler(new Euler(.3, .7, .1)));
    for (const detail of [1, 2]) {pointer(control, 'pointerdown'); pointer(control, 'pointerup'); emit(control, 'click', {detail});}
    emit(control, 'dblclick', {detail:2}); expectSamePose(orientation, new Quaternion());
  });
  it('does not mistake an out-and-back drag for a stationary click', () => {
    const initial = new Quaternion().setFromEuler(new Euler(.3, .7, .1));
    const {control, orientation} = specimen(initial);
    pointer(control, 'pointerdown'); pointer(control, 'pointermove', 180, 290); pointer(control, 'pointerup');
    emit(control, 'click', {detail:1}); pointer(control, 'pointerdown'); pointer(control, 'pointerup');
    emit(control, 'click', {detail:2}); emit(control, 'dblclick', {detail:2}); expectSamePose(orientation, initial);
  });
  it('keeps capture outside the sample and commits the release without rolling back', () => {
    const {control, orientation, onRelease, binding} = specimen();
    pointer(control, 'pointerdown'); expect(control.hasPointerCapture(1)).toBe(true); expect(control.dataset.dragging).toBe('true');
    pointer(control, 'pointermove', -100, 500); expect(binding.isDragging()).toBe(true);
    const release = pointer(control, 'pointerup', -120, 520), finished = orientation.clone();
    expect(finished.angleTo(new Quaternion())).toBeGreaterThan(.1);
    expect(control.hasPointerCapture(1)).toBe(false); expect(control.dataset.dragging).toBeUndefined(); expect(binding.isDragging()).toBe(false);
    expect(onRelease).toHaveBeenCalledExactlyOnceWith(release);
    pointer(control, 'pointermove', 200, 220); expectSamePose(orientation, finished);
  });
  it('ignores unrelated pointers throughout the captured gesture', () => {
    const {control, orientation, binding} = specimen();
    pointer(control, 'pointerdown'); pointer(control, 'pointermove', 180, 280); const beforeForeign = orientation.clone();
    for (const type of ['pointerdown', 'pointermove', 'pointerup', 'pointercancel', 'lostpointercapture']) {
      pointer(control, type, 260, 350, {pointerId:2, isPrimary:false});
      expect(binding.isDragging()).toBe(true); expectSamePose(orientation, beforeForeign);
    }
    pointer(control, 'pointerup', 190, 290); expect(binding.isDragging()).toBe(false);
  });
  it.each(['pointercancel', 'lostpointercapture', 'blur', 'window blur', 'Escape', 'cancel'])('restores the original pose on %s', reason => {
    const initial = new Quaternion().setFromEuler(new Euler(.3, .4, -.2));
    const {control, orientation, binding, onRelease} = specimen(initial);
    pointer(control, 'pointerdown'); pointer(control, 'pointermove', 220, 320); expect(orientation.angleTo(initial)).toBeGreaterThan(.1);
    if (reason==='window blur') emit(control.ownerDocument.defaultView, 'blur');
    else if (reason==='Escape') expect(keyboard(control, 'Escape').defaultPrevented).toBe(true);
    else if (reason==='cancel') binding.cancel();
    else if (reason==='blur') emit(control, 'blur');
    else pointer(control, reason);
    expectSamePose(orientation, initial); expect(binding.isDragging()).toBe(false);
    expect(control.hasPointerCapture(1)).toBe(false); expect(control.dataset.dragging).toBeUndefined(); expect(onRelease).not.toHaveBeenCalled();
  });
  it('rejects disabled, nonprimary, and non-left-button gestures', () => {
    const {control, orientation, binding} = specimen();
    control.disabled=true; pointer(control, 'pointerdown'); control.disabled=false;
    pointer(control, 'pointerdown', 140, 250, {button:2}); pointer(control, 'pointerdown', 140, 250, {isPrimary:false}); pointer(control, 'pointermove', 250, 350);
    expect(binding.isDragging()).toBe(false); expect(control.setPointerCapture).not.toHaveBeenCalled(); expectSamePose(orientation, new Quaternion());
  });
  it('supports keyboard rotation and reset without passing Enter or Space to global shortcuts', () => {
    const {control, orientation} = specimen();
    const arrow = keyboard(control, 'ArrowRight'); expect(arrow.defaultPrevented).toBe(true); expect(arrow.cancelBubble).toBe(true);
    expect(orientation.angleTo(new Quaternion())).toBeCloseTo(5*Math.PI/180);
    keyboard(control, 'Home'); expectSamePose(orientation, new Quaternion());
    keyboard(control, 'ArrowUp', {shiftKey:true}); expect(orientation.angleTo(new Quaternion())).toBeCloseTo(15*Math.PI/180);
    for (const key of ['Enter', ' ']) expect(keyboard(control, key).cancelBubble).toBe(true);
    emit(control, 'click', {detail:0}); expectSamePose(orientation, new Quaternion());
  });
  it('cancels a gesture and removes listeners when disposed', () => {
    const initial = new Quaternion().setFromEuler(new Euler(.2, -.1, .3));
    const {control, orientation, binding, invalidate} = specimen(initial);
    pointer(control, 'pointerdown'); pointer(control, 'pointermove', 200, 310); binding.dispose();
    expectSamePose(orientation, initial); expect(binding.isDragging()).toBe(false); expect(control.hasPointerCapture(1)).toBe(false);
    const calls = invalidate.mock.calls.length;
    pointer(control, 'pointerdown'); pointer(control, 'pointermove', 200, 310); pointer(control, 'pointerup', 200, 310);
    keyboard(control, 'ArrowRight'); emit(control, 'dblclick', {detail:2}); emit(control, 'click', {detail:0}); emit(control.ownerDocument.defaultView, 'blur');
    expectSamePose(orientation, initial); expect(invalidate).toHaveBeenCalledTimes(calls);
  });
});
